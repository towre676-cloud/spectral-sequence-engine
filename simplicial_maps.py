"""Geometric spectral sequences from arbitrary *finite simplicial maps*.

The filtration of |K| induced by f: K -> B is
    F_p K = {simplices s in K : dim f(s) <= p}.
It is always a filtration by subcomplexes, and its exact spectral sequence
converges to H_*(K; F_l).  Merely specifying a simplicial map does NOT
certify a Serre fibration or the E2 page of a Serre spectral sequence.

Vertices may be integers, strings, or nonempty tuples of these (needed for
products). Finite complexes are specified by generating facets; all faces
are generated, and orientations use a single deterministic vertex ordering.
"""
from __future__ import annotations

import argparse
from collections import Counter
from hashlib import sha256
from itertools import combinations
import json
from pathlib import Path

from morphisms import FilteredChainMap
from spectral_sequence import FilteredChainComplex, _rank, _prime


def _vkey(vertex):
    if type(vertex) is int:
        return (0, vertex)
    if type(vertex) is str:
        return (1, vertex)
    if type(vertex) is tuple and vertex:
        return (2, tuple(_vkey(x) for x in vertex))
    raise ValueError('vertices must be integers, strings, or nonempty tuples of these')


def _encode(vertex):
    tag = _vkey(vertex)[0]
    if tag == 0:
        return ['int', vertex]
    if tag == 1:
        return ['str', vertex]
    return ['tuple', [_encode(x) for x in vertex]]


def _decode(item):
    if not isinstance(item, list) or len(item) != 2:
        raise ValueError('invalid tagged vertex')
    tag, data = item
    if tag == 'int' and type(data) is int:
        return data
    if tag == 'str' and type(data) is str:
        return data
    if tag == 'tuple' and isinstance(data, list) and data:
        return tuple(_decode(x) for x in data)
    raise ValueError('invalid tagged vertex')


def _canonical(simplex):
    try:
        values = tuple(simplex)
    except TypeError as exc:
        raise ValueError('each simplex must be iterable') from exc
    if not values:
        raise ValueError('empty simplex is implicit, not a generating facet')
    for x in values:
        _vkey(x)
    if len(values) != len(set(values)):
        raise ValueError('simplex repeats a vertex')
    return tuple(sorted(values, key=_vkey))


class SimplicialComplex:
    """Finite abstract simplicial complex, generated by closed facets.

    Input need not list only maximal facets. Duplicates are rejected; missing
    faces are filled in automatically, not silently treated as absent.
    """

    def __init__(self, facets):
        normalized = [_canonical(s) for s in facets]
        if len(normalized) != len(set(normalized)):
            raise ValueError('duplicate generating facet')
        face_set = set()
        for facet in normalized:
            for n in range(1, len(facet) + 1):
                face_set.update(combinations(facet, n))
        self.vertices = tuple(sorted({v for s in face_set for v in s}, key=_vkey))
        self.vertex_index = {v: i for i, v in enumerate(self.vertices)}
        self.simplices = tuple(sorted(face_set, key=self._simplex_key))
        self.simplex_set = frozenset(face_set)
        # Only retain maximal facets for canonical serialization.
        maximal = tuple(s for s in normalized if not any(
            len(t) > len(s) and set(s).issubset(t) for t in normalized))
        self.facets = tuple(sorted(maximal, key=self._simplex_key))
        self.dimension = max((len(s)-1 for s in self.simplices), default=-1)

    def _simplex_key(self, simplex):
        return (len(simplex), tuple(self.vertex_index[x] for x in simplex))

    def f_vector(self):
        return dict(sorted(Counter(len(s)-1 for s in self.simplices).items()))

    def subcomplex(self, selected):
        """Return the specified closed subcomplex (reject a nonclosed selection)."""
        subset = frozenset(_canonical(s) for s in selected)
        if not subset.issubset(self.simplex_set):
            raise ValueError('subcomplex has simplex not in ambient complex')
        for simplex in subset:
            for j in range(len(simplex)):
                face = simplex[:j]+simplex[j+1:]
                if face and face not in subset:
                    raise ValueError('subcomplex is not face-closed')
        return SimplicialComplex(subset)

    def integral_chain_complex(self):
        """Signed simplicial chains over Z (total homology, no filtration)."""
        from integral import IntegralChainComplex
        degrees=[[s for s in self.simplices if len(s)==n+1]
                 for n in range(self.dimension+1)]
        boundaries={}
        for n in range(1,len(degrees)):
            positions={s:i for i,s in enumerate(degrees[n-1])}
            matrix=[[0]*len(degrees[n]) for _ in degrees[n-1]]
            for j,simplex in enumerate(degrees[n]):
                for i in range(len(simplex)):
                    face=simplex[:i]+simplex[i+1:]
                    matrix[positions[face]][j]+=(-1)**i
            boundaries[n]=matrix
        return IntegralChainComplex([len(xs) for xs in degrees],boundaries)

    def chain_complex(self, prime=2, births=None):
        """Return exact finite-field chain complex, with generator lookup.

        Default all birth values are zero (ordinary homology). The lookup is
        keyed by original labeled simplex, avoiding reliance on generated IDs.
        """
        if not _prime(prime):
            raise ValueError('field characteristic must be prime')
        if births is None:
            births = {s:0 for s in self.simplices}
        if set(births) != set(self.simplices):
            raise ValueError('birth dictionary must cover exactly all simplices')
        if any(type(b) is not int or b < 0 for b in births.values()):
            raise ValueError('births must be nonnegative integers')
        ordered = sorted(self.simplices, key=lambda s:
                         (births[s], len(s), tuple(self.vertex_index[x] for x in s)))
        names = {s:f's{i}' for i,s in enumerate(ordered)}
        records = []
        for simplex in ordered:
            b = {}
            if len(simplex) > 1:
                for j in range(len(simplex)):
                    face = simplex[:j] + simplex[j+1:]
                    b[names[face]] = (-1)**j
            records.append((names[simplex], len(simplex)-1, births[simplex], b))
        return FilteredChainComplex(records,prime=prime), names


class SimplicialMap:
    """A checked vertex map K -> B, including degeneracies.

    Each vertex of K must be mapped to a vertex of B. For every domain
    simplex, the *set* of distinct image vertices must be a base simplex.
    """

    def __init__(self, domain: SimplicialComplex, base: SimplicialComplex, vertex_map):
        if not isinstance(domain,SimplicialComplex) or not isinstance(base,SimplicialComplex):
            raise TypeError('domain and base must be SimplicialComplex instances')
        try:
            mapping = dict(vertex_map)
        except (TypeError, ValueError) as exc:
            raise ValueError('vertex map must be a mapping or iterable of pairs') from exc
        if len(mapping) != len(domain.vertices) or set(mapping) != set(domain.vertices):
            raise ValueError('vertex map must have precisely one image per domain vertex')
        if not set(mapping.values()).issubset(set(base.vertices)):
            raise ValueError('a vertex image is not a base vertex')
        self.domain, self.base = domain, base
        self.vertex_map = dict(mapping)
        self.images = {}
        self.births = {}
        for simplex in domain.simplices:
            image = tuple(sorted({mapping[x] for x in simplex}, key=_vkey))
            if image not in base.simplex_set:
                raise ValueError(f'image of domain simplex {simplex!r} is not a base simplex')
            self.images[simplex] = image
            self.births[simplex] = len(image)-1
        self.max_birth = max(self.births.values(), default=0)

    def induced_filtration(self):
        """Canonical (simplex, birth) array for a base-skeletal filtration."""
        return tuple((s,self.births[s]) for s in self.domain.simplices)

    def preimage_skeleton(self, level):
        if type(level) is not int:
            raise ValueError('skeletal level must be an integer')
        return self.domain.subcomplex(s for s in self.domain.simplices
                                      if self.births[s] <= level)

    def fiber_over_vertex(self, vertex):
        """Inverse-image subcomplex over one base vertex (possibly empty)."""
        if vertex not in self.base.vertex_index:
            raise ValueError('fiber vertex is absent from the base')
        return self.preimage_subcomplex(SimplicialComplex([(vertex,)]))

    def relative_e1_page(self, prime=2):
        """Independent same-level relative-chain calculation of E1 ranks.

        This uses the boundary restricted to birth-p simplices; no spectral
        quotient representatives or higher-page routines are called.
        """
        if not _prime(prime):
            raise ValueError('field characteristic must be prime')
        ranks={}
        grouped={}
        for simplex,birth in self.births.items():
            grouped.setdefault((birth,len(simplex)-1),[]).append(simplex)
        for p in sorted(set(self.births.values())):
            dims=[d for pp,d in grouped if pp==p]
            max_dim=max(dims)
            for d in range(max_dim+2):
                rows={face:j for j,face in enumerate(grouped.get((p,d-1),[]))}
                columns=[]
                for simplex in grouped.get((p,d),[]):
                    column=[0]*len(rows)
                    for j in range(len(simplex)):
                        face=simplex[:j]+simplex[j+1:]
                        if face in rows:
                            column[rows[face]]=(-1)**j % prime
                    columns.append(tuple(column))
                ranks[(p,d)]=_rank(columns,prime,len(rows))
        page={}
        for (p,d),cells in grouped.items():
            dim=len(cells)-ranks.get((p,d),0)-ranks.get((p,d+1),0)
            if dim<0:
                raise ArithmeticError('invalid relative boundary matrix')
            if dim:
                page[(p,d-p)]=dim
        return dict(sorted(page.items()))

    def preimage_subcomplex(self, base_subcomplex):
        """Inverse image of a *geometric* closed subsimplicial complex."""
        if not isinstance(base_subcomplex,SimplicialComplex) or not base_subcomplex.simplex_set.issubset(self.base.simplex_set):
            raise ValueError('expected a subcomplex of the base')
        return self.domain.subcomplex(s for s in self.domain.simplices
                                      if self.images[s] in base_subcomplex.simplex_set)

    def chain_complex(self, prime=2):
        return self.domain.chain_complex(prime=prime, births=self.births)[0]

    def base_skeletal_complex(self, prime=2):
        return self.base.chain_complex(prime=prime,
                                       births={s:len(s)-1 for s in self.base.simplices})[0]

    def chain_map(self, prime=2):
        """Induced oriented chain map to the base's skeletal filtration.

        A degenerate simplex maps to zero. Otherwise the coefficient is the
        permutation sign of the vertex images relative to the base ordering.
        This also checks chain commutativity and filtration preservation.
        """
        source, source_names = self.domain.chain_complex(prime=prime,births=self.births)
        target, target_names = self.base.chain_complex(
            prime=prime,births={s:len(s)-1 for s in self.base.simplices})
        images = {}
        for simplex, name in source_names.items():
            vertices = [self.vertex_map[v] for v in simplex]
            if len(set(vertices)) < len(vertices):
                images[name] = {}
            else:
                inversions = sum(_vkey(a)>_vkey(b) for i,a in enumerate(vertices)
                                 for b in vertices[i+1:])
                images[name] = {target_names[self.images[simplex]]: -1 if inversions%2 else 1}
        return FilteredChainMap(source,target,images)

    def verify(self,prime=2):
        c = self.chain_complex(prime)
        if not c.verify():
            raise ArithmeticError('page verification failed')
        if c.page(1)!=self.relative_e1_page(prime):
            raise ArithmeticError('relative E1 ranks disagree with independent computation')
        if not self.chain_map(prime).verify_naturality():
            raise ArithmeticError('simplicial chain map is not natural')
        for level in range(-1,self.max_birth+1):
            included = set(self.preimage_skeleton(level).simplices)
            if included != {s for s,b in self.births.items() if b<=level}:
                raise ArithmeticError('skeletal preimage mismatch')
        return True

    def source_data(self,prime=2):
        """Canonical JSON-portable description retaining tuple/int/string labels."""
        if not _prime(prime):
            raise ValueError('field characteristic must be prime')
        return {'schema':'simplicial-map-input-v1','prime':prime,
                'domain_facets': [[_encode(v) for v in s] for s in self.domain.facets],
                'base_facets': [[_encode(v) for v in s] for s in self.base.facets],
                'vertex_map': [[_encode(v),_encode(self.vertex_map[v])]
                               for v in self.domain.vertices]}

    @classmethod
    def from_data(cls, data):
        """Parse either readable primitive-vertex JSON or tagged receipts."""
        if not isinstance(data,dict):
            raise ValueError('map input must be a JSON object')
        schema = data.get('schema','simplicial-map-input-plain-v1')
        if schema not in ('simplicial-map-input-v1','simplicial-map-input-plain-v1'):
            raise ValueError('unsupported map input schema')
        tagged = schema == 'simplicial-map-input-v1'
        decode = _decode if tagged else lambda x:x
        try:
            d = SimplicialComplex([[decode(v) for v in s] for s in data['domain_facets']])
            b = SimplicialComplex([[decode(v) for v in s] for s in data['base_facets']])
            mapping = [(decode(a),decode(z)) for a,z in data['vertex_map']]
        except (KeyError,TypeError) as exc:
            raise ValueError('malformed simplicial-map input') from exc
        if len(mapping) != len(dict(mapping)):
            raise ValueError('duplicate vertex mapping declaration')
        return cls(d,b,mapping)

    def certificate(self,prime=2):
        """Deterministic replay receipt. Recomputed, not independently formalized."""
        if not self.verify(prime):
            raise ArithmeticError('spectral-sequence verification failed')
        chain = self.chain_complex(prime)
        pages = []
        for r in range(chain.spread+2):
            pages.append({'r':r,'groups':[[p,q,dim] for (p,q),dim in sorted(chain.page(r).items())],
                          'differential_rank':sum(x['rank'] for x in chain.differential(r).values())})
        body = {'schema':'simplicial-map-replay-v1', 'input':self.source_data(prime),
                'domain_f_vector':[[d,n] for d,n in self.domain.f_vector().items()],
                'base_f_vector':[[d,n] for d,n in self.base.f_vector().items()],
                'filtration_counts':[[d,n] for d,n in sorted(Counter(self.births.values()).items())],
                'pages':pages, 'total_betti':[[d,n] for d,n in chain.betti().items()],
                'filtered_chain_receipt_sha256':chain.certificate()['report_sha256'],
                'validated':True}
        body['report_sha256']=sha256(_packed(body).encode()).hexdigest()
        return body


def _packed(data):
    return json.dumps(data,sort_keys=True,separators=(',',':'))


def replay_simplicial_map_certificate(receipt):
    if not isinstance(receipt,dict) or receipt.get('schema')!='simplicial-map-replay-v1':
        raise ValueError('unsupported simplicial map certificate')
    body={k:v for k,v in receipt.items() if k!='report_sha256'}
    if sha256(_packed(body).encode()).hexdigest()!=receipt.get('report_sha256'):
        raise ValueError('certificate digest mismatch')
    prime=receipt['input']['prime']
    smap=SimplicialMap.from_data(receipt['input'])
    if smap.certificate(prime)!=receipt:
        raise ValueError('certificate replay mismatch')
    return True


def _staircase_paths(a,b):
    """All maximal chains from (0,0) to (a,b) in the product poset."""
    for a_steps in combinations(range(a+b),a):
        a_steps=set(a_steps)
        i=j=0
        path=[(i,j)]
        for k in range(a+b):
            if k in a_steps: i+=1
            else: j+=1
            path.append((i,j))
        yield path


def simplicial_product(base, fiber):
    """Staircase triangulation of |base| x |fiber| and projection to base.

    Vertices are tuples (base_vertex, fiber_vertex). This product has the
    correct homeomorphism type for finite ordered simplicial complexes.
    """
    if not isinstance(base,SimplicialComplex) or not isinstance(fiber,SimplicialComplex):
        raise TypeError('product factors must be simplicial complexes')
    facets=set()
    for a in base.facets:
        for b in fiber.facets:
            for path in _staircase_paths(len(a)-1,len(b)-1):
                facets.add(tuple((a[i],b[j]) for i,j in path))
    total=SimplicialComplex(facets)
    return SimplicialMap(total,base,{v:v[0] for v in total.vertices})


def _validate_automorphism(fiber,automorphism):
    if not isinstance(fiber,SimplicialComplex):
        raise TypeError('fiber must be a simplicial complex')
    try: g=dict(automorphism)
    except (TypeError,ValueError) as exc:
        raise ValueError('automorphism must be a mapping') from exc
    if set(g)!=set(fiber.vertices) or set(g.values())!=set(fiber.vertices) or len(g)!=len(fiber.vertices):
        raise ValueError('automorphism must permute exactly the fiber vertices')
    for s in fiber.simplices:
        if tuple(sorted((g[v] for v in s),key=_vkey)) not in fiber.simplex_set:
            raise ValueError('vertex permutation fails to preserve fiber simplices')
    return g


def mapping_torus_projection(fiber, automorphism, segments=3):
    """Simplicial mapping torus over a cyclic n-gon (n>=3).

    Build prisms over each oriented fiber simplex at j->j+1, identifying
    the final top face (n,v) with (0,g(v)). Returns its map to the base
    n-cycle. A nontrivial g may induce nontrivial homology local systems.
    """
    g=_validate_automorphism(fiber,automorphism)
    if type(segments) is not int or segments < 3:
        raise ValueError('mapping torus requires at least three base segments')
    base=SimplicialComplex([(j,(j+1)%segments) for j in range(segments)])
    facets=set()
    for j in range(segments):
        for face in fiber.facets:
            for path in _staircase_paths(1,len(face)-1):
                verts=[]
                for i,k in path:
                    v=face[k]
                    verts.append((j,v) if i==0 else
                                 ((j+1,v) if j+1<segments else (0,g[v])))
                facets.add(tuple(verts))
    total=SimplicialComplex(facets)
    return SimplicialMap(total,base,{v:v[0] for v in total.vertices})


def monodromy_on_homology(fiber, automorphism, prime=2):
    """Induced matrices of simplicial automorphism on H_q(fiber; F_prime).

    Returned matrices are column-oriented, in deterministic computed bases.
    """
    g=_validate_automorphism(fiber,automorphism)
    # The mapping defined by g is an ordinary simplicial chain map; homology
    # here is *unfiltered*, unlike the base-skeletal map's filtration.
    c, names=fiber.chain_complex(prime=prime)
    images={}
    for s, name in names.items():
        vertices=[g[v] for v in s]
        inversions=sum(_vkey(a)>_vkey(b) for i,a in enumerate(vertices) for b in vertices[i+1:])
        target=tuple(sorted(vertices,key=_vkey))
        images[name]={names[target]: -1 if inversions%2 else 1}
    chain_map=FilteredChainMap(c,c,images)
    if not chain_map.verify_naturality():
        raise ArithmeticError('automorphism fails naturality')
    return {q:chain_map.on_page(1)[(0,q)] for q in c.betti()}


def circle_local_system_e2(fiber, automorphism, prime=2):
    """Expected E2 page of the circle-base bundle with this monodromy.

    For V=H_q(F;F_prime), H_0(S1;V)=coker(T-I) and
    H_1(S1;V)=ker(T-I). Both have dimension dim(V)-rank(T-I).
    Used as an *independent* check of the mapping-torus filtration.
    """
    matrices=monodromy_on_homology(fiber,automorphism,prime)
    page={}
    for q,columns in matrices.items():
        n=len(columns)
        difference=[tuple((columns[j][i]-int(i==j))%prime for i in range(n))
                    for j in range(n)]
        dim=n-_rank(difference,prime,n)
        if dim:
            page[(0,q)]=dim
            page[(1,q)]=dim
    return page


def _example(name,prime=2):
    if name=='hopf':
        from research.hopf_fibration import hopf_simplicial_map
        return hopf_simplicial_map()
    if name in ('torus','klein'):
        fiber=SimplicialComplex([(0,1),(1,2),(0,2)])
        return mapping_torus_projection(fiber,{0:0,1:1,2:2} if name=='torus'
                                        else {0:1,1:0,2:2})
    if name=='product-sphere':
        base=SimplicialComplex([tuple(face) for face in ('abc','abd','acd','bcd')])
        fiber=SimplicialComplex([(0,1),(1,2),(0,2)])
        return simplicial_product(base,fiber)
    if name in ('sphere-torus','twisted-sphere-torus'):
        fiber=SimplicialComplex([tuple(face) for face in ('abc','abd','acd','bcd')])
        return mapping_torus_projection(fiber,
            {v:v for v in fiber.vertices} if name=='sphere-torus' else
            {'a':'b','b':'a','c':'c','d':'d'})
    raise ValueError('unknown simplicial-map example')


def main(argv=None):
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('input',nargs='?',help='JSON map with facets and vertex-map pairs')
    parser.add_argument('--example',choices=('hopf','torus','klein','product-sphere',
                                             'sphere-torus','twisted-sphere-torus'))
    parser.add_argument('--prime',type=int,help='override input field characteristic (default 2)')
    parser.add_argument('--certificate',help='write deterministic geometric replay receipt')
    parser.add_argument('--replay',help='replay existing geometric receipt')
    args=parser.parse_args(argv)
    if args.replay:
        replay_simplicial_map_certificate(json.loads(Path(args.replay).read_text(encoding='utf-8')))
        print('Geometric replay: PASS')
        return
    if (args.input is None)==(args.example is None):
        parser.error('select exactly one input or example')
    data=(json.loads(Path(args.input).read_text(encoding='utf-8'))
          if args.input else None)
    prime=args.prime if args.prime is not None else (data.get('prime',2) if data else 2)
    mapping=(_example(args.example,prime) if args.example else SimplicialMap.from_data(data))
    receipt=mapping.certificate(prime)
    print(f'Geometric map: {len(mapping.domain.simplices)} domain simplices; '
          f'{len(mapping.base.simplices)} base simplices; F_{prime}')
    for page in receipt['pages']:
        print(f'E_{page["r"]}: {page["groups"]}; '
              f'rank(d_{page["r"]})={page["differential_rank"]}')
    print(f'Total Betti: {receipt["total_betti"]}; exact verification: PASS')
    if args.certificate:
        Path(args.certificate).write_text(json.dumps(receipt,indent=2,sort_keys=True)+'\n',encoding='utf-8')
        print(f'Certificate: {args.certificate}')


if __name__=='__main__':
    main()
